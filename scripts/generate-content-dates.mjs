/**
 * Build-time last-edit dates for schema dateModified + visible "Updated" labels.
 * Source of truth = file mtime of the content data modules (not hardcoded strings).
 *
 * Run: node scripts/generate-content-dates.mjs
 * Wired into build:netlify / sitemap generation.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const outDir = path.join(root, 'src/marketing/data/generated');
const outFile = path.join(outDir, 'contentDates.ts');

function isoDateFromMtime(relPath) {
  const abs = path.join(root, relPath);
  if (!fs.existsSync(abs)) {
    throw new Error(`Missing content file for dates: ${relPath}`);
  }
  const mtime = fs.statSync(abs).mtime;
  return mtime.toISOString().slice(0, 10);
}

function maxIso(...dates) {
  return dates.sort().at(-1);
}

const compareCompetitors = isoDateFromMtime('src/marketing/data/compareCompetitors.ts');
const compareFeatureMatrix = isoDateFromMtime('src/marketing/data/compareFeatureMatrix.ts');
const compareThreeWayPage = isoDateFromMtime('src/marketing/pages/CompareThreeWayPage.tsx');
const blogPosts = isoDateFromMtime('src/data/blogPosts.ts');
const features = isoDateFromMtime('src/marketing/data/features.ts');
const productPages = isoDateFromMtime('src/marketing/data/productPages.ts');
const billingCatalog = isoDateFromMtime('src/marketing/lib/billingCatalog.ts');

const compareTwoWay = maxIso(compareCompetitors, compareFeatureMatrix);
const compareThreeWay = maxIso(compareThreeWayPage, compareFeatureMatrix);
const featurePages = maxIso(features, productPages);

const source = `/**
 * AUTO-GENERATED by scripts/generate-content-dates.mjs — do not edit by hand.
 * Regenerated on each build from content file mtimes.
 */
export const CONTENT_DATES = {
  /** Last edit of compare competitor data (+ feature matrix). */
  compareTwoWay: '${compareTwoWay}',
  /** Last edit of 3-way compare page (+ feature matrix). */
  compareThreeWay: '${compareThreeWay}',
  /** Last edit of blogPosts.ts (used as Article dateModified fallback). */
  blogPosts: '${blogPosts}',
  /** Last edit of feature / product page content. */
  featurePages: '${featurePages}',
  /** Last edit of published plan catalog (pricing Offers). */
  pricing: '${billingCatalog}',
} as const;

export type ContentDateKey = keyof typeof CONTENT_DATES;
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, source, 'utf8');
console.log(`✅ Wrote ${outFile}`);
console.log(
  `   compareTwoWay=${compareTwoWay}  compareThreeWay=${compareThreeWay}  blogPosts=${blogPosts}  featurePages=${featurePages}  pricing=${billingCatalog}`,
);
